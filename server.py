@app.post("/api/clean/propose")
def clean_propose():
    ws = get_ws()
    if not ws: return jsonify({"error": "Upload a CSV first."}), 400
    issues = scan(ws)
    proposal = W.build_smart_clean_proposal(ws, issues)
    # Run the same detectors against an isolated simulated copy to produce an honest before/proposed comparison.
    simulated = ws.working_df.copy(deep=True)
    for change in proposal.get("changes", []):
        row, col = int(change.get("row", -1)), str(change.get("column", ""))
        if row in simulated.index and col in simulated.columns:
            simulated.at[row, col] = str(change.get("proposed", ""))
    after_issues = D.scan_dataset(simulated, ws.rules_df).get("issues", [])
    def counts_for(items):
        counts = {"missing": 0, "confirmed": 0, "potential": 0, "duplicate": 0}
        for item in items:
            if item.get("type") == "Missing value": counts["missing"] += 1
            elif item.get("type") == "Duplicate record": counts["duplicate"] += 1
            elif item.get("severity") == D.SEV_CONFIRMED: counts["confirmed"] += 1
            else: counts["potential"] += 1
        return counts
    proposal["current_issue_counts"] = counts_for(issues)
    proposal["simulated_issue_counts"] = counts_for(after_issues)
    proposal["simulation_note"] = "The proposed result was scanned on a temporary copy; no working data has changed."
    ws.pending = proposal
    persist_ws(session.get("workspace_key"), ws)
    return jsonify({"proposal": proposal, **payload(ws)})


@app.post("/api/manual/propose")
def manual_propose():
    ws = get_ws()
    if not ws: return jsonify({"error": "Upload a CSV first."}), 400
    data = request.get_json(force=True)
    col, row = str(data.get("column", "")), int(data.get("row", -1))
    action, custom = str(data.get("action", "custom")), str(data.get("value", ""))
    if col not in ws.working_df.columns or row not in ws.working_df.index:
        return jsonify({"error": "Selected cell was not found."}), 400
    original = ws.working_df.at[row, col]
    if action == "mean":
        nums = [D.parse_number(v) for v in ws.working_df[col].tolist() if not D.is_missing(v)]
        nums = [x for x in nums if x is not None and x >= 0]
        if not nums: return jsonify({"error": "No valid non-negative numeric values are available for the mean."}), 400
        value = str(round(sum(nums)/len(nums), 6)).rstrip("0").rstrip(".")
        mask = ws.working_df[col].map(lambda v: (D.parse_number(v) is not None and D.parse_number(v) < 0))
        changes = [{"row": int(r), "column": col, "original": str(ws.working_df.at[r,col]), "proposed": value,
                    "reason": "Replaced a negative value with the mean of valid non-negative values.", "confidence": "Review"}
                   for r in ws.working_df.index[mask]]
    elif action == "median":
        nums = [D.parse_number(v) for v in ws.working_df[col].tolist() if not D.is_missing(v)]
        nums = [x for x in nums if x is not None and x >= 0]
        if not nums: return jsonify({"error": "No valid non-negative numeric values are available for the median."}), 400
        import statistics
        value = str(statistics.median(nums))
        mask = ws.working_df[col].map(lambda v: (D.parse_number(v) is not None and D.parse_number(v) < 0))
        changes = [{"row": int(r), "column": col, "original": str(ws.working_df.at[r,col]), "proposed": value,
                    "reason": "Replaced a negative value with the median of valid non-negative values.", "confidence": "Review"}
                   for r in ws.working_df.index[mask]]
    elif action == "group":
        key = D.normalize_key(str(original))
        changes=[]
        for r, v in ws.working_df[col].items():
            if D.normalize_key(str(v)) == key:
                changes.append({"row": int(r), "column": col, "original": str(v), "proposed": custom,
                                "reason": "Bulk edit of matching normalised values.", "confidence": "User supplied"})
    elif action == "missing_group":
        changes=[]
        for r, v in ws.working_df[col].items():
            if D.is_missing(v) or str(v).strip().lower() in D.PLACEHOLDERS:
                changes.append({"row": int(r), "column": col, "original": str(v), "proposed": custom,
                                "reason": "Bulk edit of missing markers and placeholder-like values.", "confidence": "User supplied"})
    else:
        changes = [{"row": row, "column": col, "original": str(original), "proposed": custom,
                    "reason": "User-supplied correction.", "confidence": "User supplied"}]
    ws.pending = {"changes": changes, "errors": [], "warnings": [], "rows": sorted({c["row"] for c in changes}),
                  "columns": [col], "issue_ids": [], "kind": "edit", "action": "manual_edit",
                  "action_label": f"Manual Clean · {action}", "created_at": W.now_iso()}
    persist_ws(session.get("workspace_key"), ws)
    return jsonify({"proposal": ws.pending, **payload(ws)})


