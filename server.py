DB_PATH = Path(__file__).with_name("datasleuth_history.sqlite3")


def db():
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    conn.execute("""CREATE TABLE IF NOT EXISTS investigations (
        id TEXT PRIMARY KEY, name TEXT NOT NULL, pinned INTEGER NOT NULL DEFAULT 0,
        updated_at TEXT NOT NULL, snapshot BLOB NOT NULL)""")
    conn.commit()
    return conn


def persist_ws(key, ws):
    if not key or not ws:
        return
    snapshot = pickle.dumps(ws, protocol=pickle.HIGHEST_PROTOCOL)
    now = datetime.now(timezone.utc).isoformat()
    with db() as conn:
        conn.execute("""INSERT INTO investigations(id,name,pinned,updated_at,snapshot)
            VALUES(?,?,?,?,?) ON CONFLICT(id) DO UPDATE SET name=excluded.name,
            updated_at=excluded.updated_at,snapshot=excluded.snapshot""",
            (key, ws.name, 0, now, snapshot))


def get_ws():
    key = session.get("workspace_key")
    if not key:
        return None
    if key in WORKSPACES:
        return WORKSPACES[key]
    with db() as conn:
        row = conn.execute("SELECT snapshot FROM investigations WHERE id=?", (key,)).fetchone()
    if not row:
        return None
    try:
        ws = pickle.loads(row["snapshot"])
    except Exception:
        return None
    WORKSPACES[key] = ws
    return ws


def history_payload():
    with db() as conn:
        rows = conn.execute("SELECT id,name,pinned,updated_at FROM investigations ORDER BY pinned DESC, updated_at DESC LIMIT 50").fetchall()
    return [dict(id=r["id"], name=r["name"], pinned=bool(r["pinned"]), updated_at=r["updated_at"]) for r in rows]


def json_value(v):
    if pd.isna(v): return ""
    return str(v)


def scan(ws):
    return D.scan_dataset(ws.working_df, ws.rules_df).get("issues", [])


def issue_json(i):
    out = {}
    for k, v in i.items():
        if hasattr(v, "item"):
            try: v = v.item()
            except Exception: pass
        out[k] = json_value(v) if k == "value" else v
    return out


def summary(df, issues):
    rows = []
    for col in df.columns:
        subset = [i for i in issues if i.get("column") == col]
        rows.append({"column": str(col),
                     "missing": sum(i.get("type") == "Missing value" for i in subset),
                     "anomalies": sum(i.get("type") not in ("Missing value", "Duplicate record") for i in subset),
                     "duplicates": sum(i.get("type") == "Duplicate record" for i in subset)})
    return rows


def table_rows(ws, issues):
    by_cell = {}
    dup_rows = set()
    priority = {D.SEV_FACT: 1, D.SEV_POTENTIAL: 2, D.SEV_CONFIRMED: 3}
    for i in issues:
        row, col = int(i.get("row", -1)), str(i.get("column", ""))
        if col == D.ENTIRE_ROW:
            dup_rows.add(row); continue
        key = (row, col)
        if key not in by_cell or priority.get(i.get("severity"), 0) > priority.get(by_cell[key].get("severity"), 0):
            by_cell[key] = i
    changed = {(int(a.get("Row")), str(a.get("Column"))) for a in ws.audit if a.get("Operation") == "edit_cell" and a.get("Status") == "applied"}
    result = []
    for idx, (_, row) in enumerate(ws.working_df.iterrows(), start=1):
        cells = []
        row_id = int(ws.working_df.index[idx-1])
        for col in ws.working_df.columns:
            val = json_value(row[col]); issue = by_cell.get((row_id, str(col)))
            kind = "changed" if (row_id, str(col)) in changed else ""
            if issue:
                t = issue.get("type", "")
                if t == "Missing value": kind = "missing"
                elif issue.get("severity") == D.SEV_CONFIRMED: kind = "confirmed"
                else: kind = "potential"
            if row_id in dup_rows and not issue: kind = "duplicate"
            cells.append({"column": str(col), "value": val, "kind": kind, "issue": issue_json(issue) if issue else None, "row": row_id})
        result.append({"row": row_id, "cells": cells, "duplicate": row_id in dup_rows})
    return result


def algorithm_trace(ws, issues):
    # Hash table trace is generated by the same custom implementation used for duplicate detection.
    records = [(int(idx), tuple("" if pd.isna(v) else str(v) for v in row))
               for idx, row in zip(ws.working_df.index, ws.working_df.astype(object).values.tolist())]
    dup_result = find_duplicates(records, num_buckets=101, max_trace=1500)
    missing_trace = []
    for idx, row in ws.working_df.iterrows():
        missing_cells = [str(col) for col in ws.working_df.columns if D.is_missing(row[col])]
        missing_trace.append({"row": int(idx), "checked": len(ws.working_df.columns),
                              "missing_columns": missing_cells, "found": bool(missing_cells)})
        if len(missing_trace) >= 1500:
            break
    # Use the custom max-heap to order actual detected issues by severity score.
    heap = MaxHeap()
    for n, issue in enumerate(issues):
        severity = str(issue.get("severity", ""))
        issue_type = str(issue.get("type", ""))
        score = D.priority_score(severity, issue_type)
        heap.push((score, -int(issue.get("row", 0)), -n), {
            "row": int(issue.get("row", 0)), "column": str(issue.get("column", "")),
            "type": str(issue.get("type", "Issue")), "score": score,
            "id": str(issue.get("id", "")), "n": n})
    heap_steps = list(heap.log)
    # Snapshot the real internal heap array before extraction so the UI can draw
    # the actual binary-heap tree (not a sorted list masquerading as a heap).
    snapshot = heap.snapshot()
    heap_array = [
        {"index": i, "score": entry[0][0], **entry[1]}
        for i, entry in enumerate(snapshot)
    ]
    n_inserts = len(heap_steps)
    priority_order = []
    while len(heap) and len(priority_order) < 1500:
        _, item = heap.pop()
        priority_order.append(item)
    extract_log = heap.log[n_inserts:]
    return {"hash_steps": dup_result.steps[:1500], "hash_stats": dup_result.stats,
            "missing_steps": missing_trace, "heap_steps": heap_steps[:1500],
            "heap_array": heap_array[:127], "priority_order": priority_order,
            "heap_view": heap_view(issues, snapshot, heap_steps, extract_log)}


# ---- Max-heap visualisation payload ---------------------------------------------------
HEAP_VIEW_MAX_NODES = 1000      # heap positions sent to the browser (size is always reported)
HEAP_VIEW_MAX_INSERT_OPS = 300  # insertion log entries sent
HEAP_VIEW_MAX_EXTRACT_OPS = 100  # extract-max log entries sent
HEAP_COMPARATOR = ("Keys are tuples (priority score, -row, -detection order) compared with Python's "
                   "tuple '>'. A higher score is closer to the root; equal scores are ordered by the "
                   "smaller row number, then by the issue that was detected first.")


def priority_breakdown(severity, issue_type):
    """Split detectors.priority_score() into its two documented parts (same weight tables)."""
    sev_w = D.SEVERITY_WEIGHT.get(severity, 0)
    type_w = D.TYPE_WEIGHT.get(issue_type, 0)
    return {"severity": severity, "severity_weight": sev_w, "type": issue_type, "type_weight": type_w,
            "total": D.priority_score(severity, issue_type)}


def _compact_op(entry):
    """Heap log entry -> JSON-safe dict without the bulky 'array_head' text."""
    issue = entry.get("issue") or {}
    moved = entry.get("moved_to_root")
    return {
        "step": entry.get("step"), "operation": entry.get("operation"),
        "issue": {k: issue.get(k) for k in ("row", "column", "type", "score", "id")},
        "key": list(entry.get("key", ())), "size": entry.get("size"),
        "swap_pairs": entry.get("swap_pairs", []), "comparisons": [
            {**c, "key": list(c["key"]), "against_key": list(c["against_key"])}
            for c in entry.get("comparisons", [])],
        "final_index": entry.get("final_index"),
        "moved_to_root": ({"from_index": moved["from_index"], "key": list(moved["key"]),
                           "issue": {k: moved["issue"].get(k) for k in ("row", "column", "type", "score", "id")}}
                          if moved else None),
    }


def heap_view(issues, snapshot, insert_log, extract_log):
    """Everything the heap visualisation needs, taken from the real MaxHeap instance."""
    nodes = []
    for i, (key, payload) in enumerate(snapshot[:HEAP_VIEW_MAX_NODES]):
        src = issues[payload["n"]] if 0 <= payload.get("n", -1) < len(issues) else {}
        bd = priority_breakdown(str(src.get("severity", "")), str(src.get("type", "")))
        nodes.append({
            "index": i, "score": key[0], "key": list(key), "id": payload.get("id"),
            "row": payload.get("row"), "column": payload.get("column"), "type": payload.get("type"),
            "severity": src.get("severity") or None, "value": json_value(src.get("value", "")),
            "reason": src.get("reason") or None, "breakdown": bd,
            "explanation": (f"Priority {bd['total']} = severity weight {bd['severity_weight']} "
                            f"({bd['severity'] or 'unknown severity'}) + issue-type weight {bd['type_weight']} "
                            f"({bd['type'] or 'unknown type'})."),
            "parent": None if i == 0 else (i - 1) // 2,
            "children": [c for c in (2 * i + 1, 2 * i + 2) if c < len(snapshot)],
        })
    return {
        "size": len(snapshot), "array": nodes, "array_returned": len(nodes),
        "array_truncated": len(snapshot) > len(nodes),
        "comparator": HEAP_COMPARATOR,
        "weights": {"severity": D.SEVERITY_WEIGHT, "type": D.TYPE_WEIGHT},
        "snapshot_note": "Tree and array show the heap after the last insertion and before any extract-max.",
        "inserts_total": len(insert_log), "extracts_total": len(extract_log),
        "insert_ops": [_compact_op(e) for e in insert_log[:HEAP_VIEW_MAX_INSERT_OPS]],
        "extract_ops": [_compact_op(e) for e in extract_log[:HEAP_VIEW_MAX_EXTRACT_OPS]],
    }


def payload(ws):
    issues = scan(ws)
    traces = algorithm_trace(ws, issues)
    return {"name": ws.name, "workspace_id": session.get("workspace_key"), "columns": [str(c) for c in ws.working_df.columns],
            "rows": table_rows(ws, issues), "summary": summary(ws.working_df, issues),
            "issues": [issue_json(i) for i in issues], "issue_count": len(issues),
            "row_count": len(ws.working_df), "column_count": len(ws.working_df.columns),
            "pending": ws.pending, "audit_count": len(ws.audit),
            "dsa": {**dsa_summary(ws.working_df), **traces}}


def dsa_summary(df):
    try:
        records = [(int(idx), tuple(map(str, row))) for idx, row in zip(df.index, df.astype(str).values.tolist())]
        dup = find_duplicates(records, num_buckets=101)
        dup_count = dup.stats.get("duplicate_rows", 0)
    except Exception:
        dup_count = sum(1 for i in D.scan_dataset(df, D.default_rules(df)).get("issues", []) if i.get("type") == "Duplicate record")
    return {"hash_table": "Custom separate-chaining hash table", "heap": "Custom binary max-heap", "rows_scanned": len(df), "duplicates_detected": dup_count}


